import type { Photo } from "@/lib/types";

function normalizeTitle(fileName: string) {
  const title = fileName
    .replace(/\(1\)/g, "")
    .replace(/^WhatsApp Image\s*/i, "WhatsApp ")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return title || fileName;
}

function parseDate(fileName: string) {
  const imageMatch = fileName.match(/^IMG-(\d{8})-WA/);
  if (imageMatch) {
    const d = imageMatch[1];
    return `${d.slice(0, 4)}-${d.slice(4, 6)}-${d.slice(6, 8)}`;
  }

  const whatsappMatch = fileName.match(/^WhatsApp Image (\d{4})-(\d{2})-(\d{2})/);
  if (whatsappMatch) {
    return `${whatsappMatch[1]}-${whatsappMatch[2]}-${whatsappMatch[3]}`;
  }

  return "Unknown date";
}

